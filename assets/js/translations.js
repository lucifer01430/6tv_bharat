window.getSelectedLanguage = function getSelectedLanguage() {
  return localStorage.getItem("selectedLanguage") || "hi";
};

window.setSelectedLanguage = function setSelectedLanguage(language) {
  localStorage.setItem("selectedLanguage", language);
  window.applyTranslations(language);
  document.dispatchEvent(new CustomEvent("languagechange", { detail: { language } }));
};

window.t = function translate(key, language = window.getSelectedLanguage()) {
  return window.translations?.[language]?.[key] || window.translations?.hi?.[key] || "";
};

window.applyTranslations = function applyTranslations(language = window.getSelectedLanguage()) {
  document.documentElement.lang = language;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = window.translations?.[language]?.[element.dataset.i18n];
    if (value) element.textContent = value;
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const value = window.translations?.[language]?.[element.dataset.i18nPlaceholder];
    if (value) element.setAttribute("placeholder", value);
  });

  document.querySelectorAll("[data-i18n-title]").forEach((element) => {
    const value = window.translations?.[language]?.[element.dataset.i18nTitle];
    if (value) element.setAttribute("title", value);
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const value = window.translations?.[language]?.[element.dataset.i18nAriaLabel];
    if (value) element.setAttribute("aria-label", value);
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const value = window.translations?.[language]?.[element.dataset.i18nAlt];
    if (value) element.setAttribute("alt", value);
  });

  document.querySelectorAll("h1,h2,h3,h4,h5,h6,p,a,span,strong,button,label,li,small").forEach((element) => {
    if (element.dataset.i18n || element.children.length) return;
    if (!element.dataset.originalText) element.dataset.originalText = element.textContent.trim();
    const original = element.dataset.originalText;
    if (!original || /6TV भारत|news@6tvbharat\.com|\+91|^\d/.test(original)) return;
    const translated = window.staticTextTranslations?.[original];
    element.textContent = language === "en" && translated ? translated : original;
  });

  document.querySelectorAll(".language-option").forEach((option) => {
    option.classList.toggle("active", option.dataset.language === language);
  });

  const toggle = document.querySelector("[data-language-toggle]");
  if (toggle) toggle.lastChild.textContent = language === "hi" ? " हिन्दी" : " English";

  window.updatePageMetadata?.(language);
};
